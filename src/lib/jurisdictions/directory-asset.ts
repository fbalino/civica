import type { JurisdictionDirectoryArtifact } from "./directory";

/**
 * Public jurisdiction directory asset (`jurisdiction-directory-asset/v1`).
 *
 * Every country search on the site (header, footer, home hero, 404 page, and
 * the country pages' jump search) reads this ONE trimmed list. It is derived
 * from the checked `directory.generated.json` artifact (CAC-003), written to
 * `public/data/` under a content-addressed filename, and fetched once per
 * page session by `useJurisdictionDirectory` — only when a reader starts to
 * use a search field. Pages therefore carry no country list in their HTML or
 * React Server Component payload.
 *
 * The filename embeds the asset schema version plus the first 12 hex
 * characters of the checked artifact's `rowsSha256`, so a changed list always
 * produces a new URL and the file can be cached as immutable. A change to the
 * trimmed row shape must bump the `v1` segment. Regenerate with
 * `npm run generate:jurisdiction-directory-asset`;
 * `npm run validate:jurisdiction-directory` fails on any drift.
 */
export const JURISDICTION_DIRECTORY_ASSET_VERSION =
  "jurisdiction-directory-asset/v1";

/** Only the fields a country search displays or matches on. */
export type JurisdictionDirectoryAssetRow = {
  slug: string;
  name: string;
  iso2: string | null;
  capital: string | null;
  statusLabel: string;
  /** True only for `sovereign_state` rows (the footer's search universe). */
  sovereign: boolean;
};

export type JurisdictionDirectoryAsset = {
  schemaVersion: typeof JURISDICTION_DIRECTORY_ASSET_VERSION;
  rowsSha256: string;
  rows: JurisdictionDirectoryAssetRow[];
};

/** Repository directory (relative to the project root) holding the asset. */
export const JURISDICTION_DIRECTORY_ASSET_DIR = "public/data";

/** Filename pattern shared by the generator and validator. */
export const JURISDICTION_DIRECTORY_ASSET_FILE_PATTERN =
  /^jurisdiction-directory\.[^/]+\.json$/;

export function jurisdictionDirectoryAssetPath(rowsSha256: string): string {
  return `/data/jurisdiction-directory.v1-${rowsSha256.slice(0, 12)}.json`;
}

export function buildJurisdictionDirectoryAsset(
  artifact: Pick<JurisdictionDirectoryArtifact, "rowsSha256" | "rows">,
): JurisdictionDirectoryAsset {
  return {
    schemaVersion: JURISDICTION_DIRECTORY_ASSET_VERSION,
    rowsSha256: artifact.rowsSha256,
    rows: artifact.rows.map((row) => ({
      slug: row.slug,
      name: row.name,
      iso2: row.iso2,
      capital: row.capital,
      statusLabel: row.statusLabel,
      sovereign: row.statusType === "sovereign_state",
    })),
  };
}

/** Exact bytes written to disk: compact JSON plus a trailing newline. */
export function serializeJurisdictionDirectoryAsset(
  asset: JurisdictionDirectoryAsset,
): string {
  return `${JSON.stringify(asset)}\n`;
}

/** Source text of the generated module that tells the client the asset URL. */
export function renderJurisdictionDirectoryAssetModule(path: string): string {
  return [
    "// Generated by scripts/generate-jurisdiction-directory-asset.ts. Do not edit.",
    "// The content-addressed URL of the public jurisdiction directory asset.",
    `export const JURISDICTION_DIRECTORY_ASSET_PATH = ${JSON.stringify(path)};`,
    "",
  ].join("\n");
}
